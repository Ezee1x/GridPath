import type { EvidenceReference, FieldObservation } from "../intake/types";
export interface ElectricalSite {
  siteKey: string;
  address: string;
  parcelFeatureId: string | null;
  parcelId?: string | null;
  townId?: number | null;
}
export interface AdapterResult {
  adapter: string;
  status: "found" | "empty" | "unavailable" | "error";
  message: string;
  sourceUrl: string;
}
export interface ElectricalPermit {
  id: string;
  category: string;
  issuedDate: string | null;
  filingDate: null;
  status: string;
  address: string;
  parcelId: string;
  description: string;
  sourceUrl: string;
  documentUrls: string[];
  documentAvailability: "Not exposed by this dataset";
  condition: "Historical record; current installation unknown";
  matchingMethod: string;
}
/** A customer request generated by discovery, kept after it is resolved. */
export interface ElectricalRequestEntry {
  fieldId: string;
  label: string;
  request: string;
  createdAt: string;
  status: "Open" | "Completed" | "Superseded";
  resolvedAt?: string;
  resolution?: string;
}
/** Summary of an earlier search, kept when a new search replaces it. */
export interface ElectricalSearchSummary {
  retrievedAt: string;
  municipality: string | null;
  queryAddress: string | null;
  utilityCandidates: string[];
  permitCount: number;
  adapters: { adapter: string; status: AdapterResult["status"] }[];
  replacedAt: string;
}
export interface ElectricalDiscovery {
  siteKey: string;
  parcelFeatureId: string | null;
  /** When the public sources were searched. Never changed by later reconciliation. */
  retrievedAt: string;
  /** Address text sent to the search. */
  queryAddress?: string | null;
  /** Why these results no longer describe this record; null or absent when current. */
  stale?: string | null;
  requestHistory?: ElectricalRequestEntry[];
  previousSearches?: ElectricalSearchSummary[];
  publicAddress: string | null;
  municipality: string | null;
  adapters: AdapterResult[];
  utilityCandidates: {
    name: string;
    townId: number;
    recordId: string;
    sourceKey: string;
  }[];
  permits: ElectricalPermit[];
  observations: { fieldId: string; observation: FieldObservation }[];
  sources: Record<string, EvidenceReference>;
  fieldResults: Record<
    string,
    { statuses: string[]; reason: string; sourceKeys: string[] }
  >;
  customerRequests: {
    fieldId: string;
    label: string;
    request: string;
    owner: string;
  }[];
  documentEvidence: {
    fieldId: string;
    sourceKeys: string[];
    availableFiles: number;
  }[];
}
